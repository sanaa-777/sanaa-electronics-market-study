# -*- coding: utf-8 -*-
"""Build Arabic DOCX market report from collected OpenSooq Sanaa data."""
import json
from docx import Document
from docx.shared import Pt, RGBColor, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

stats = json.load(open("stats.json", encoding="utf-8"))

doc = Document()
style = doc.styles["Normal"]
style.font.name = "Arial"
style.font.size = Pt(11)
style.element.rPr.rFonts.set(qn("w:cs"), "Arial")

def rtl(p):
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    pPr = p._p.get_or_add_pPr()
    bidi = OxmlElement("w:bidi"); bidi.set(qn("w:val"), "1")
    pPr.append(bidi)
    return p

def H(text, level=1):
    p = doc.add_heading("", level=level)
    r = p.add_run(text)
    r.font.color.rgb = RGBColor(0x1F, 0x4E, 0x5F)
    rtl(p)
    return p

def P(text, bold=False):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = bold
    rtl(p)
    return p

def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = h
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        for r in c.paragraphs[0].runs: r.bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = str(v)
            cells[i].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
            rtl(cells[i].paragraphs[0])
    return t

