def med_price(matched):
    vals = []
    for a in matched:
        m = re.sub(r"[^\d]", "", a["price"] or "")
        if m:
            v = int(m)
            if 500 <= v <= 60_000_000:  # filter token prices & typos
                vals.append(v)
    return int(statistics.median(vals)) if len(vals) >= 3 else None

