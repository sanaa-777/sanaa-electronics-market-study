from docx.shared import Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

rows = json.load(open("top200_rows.json", encoding="utf-8"))
doc = Document()
style = doc.styles["Normal"]; style.font.name = "Arial"; style.font.size = Pt(11)
style.element.rPr.rFonts.set(qn("w:cs"), "Arial")

def rtl(p):
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    pPr = p._p.get_or_add_pPr(); bidi = OxmlElement("w:bidi"); bidi.set(qn("w:val"), "1")
    pPr.append(bidi); return p

def H(t, lvl=1):
    p = doc.add_heading("", level=lvl); r = p.add_run(t)
    r.font.color.rgb = RGBColor(0x1F,0x4E,0x5F); rtl(p); return p

def P(t, bold=False):
    p = doc.add_paragraph(); r = p.add_run(t); r.bold = bold; rtl(p); return p

def table(headers, data):
    t = doc.add_table(rows=1, cols=len(headers)); t.style = "Light Grid Accent 1"
    for i,h in enumerate(headers):
        c = t.rows[0].cells[i]; c.text = h
        for r in c.paragraphs[0].runs: r.bold = True
        rtl(c.paragraphs[0])
    for row in data:
        cells = t.add_row().cells
        for i,v in enumerate(row):
            cells[i].text = str(v); rtl(cells[i].paragraphs[0])
    return t

